import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[];
const ok=(name,condition)=>checks.push([name,!!condition]);
const helper=read('src/modules/services/serviceDaily.ts');
const wizard=read('src/modules/quotes/components/QuoteWizard.tsx');
const calc=read('src/modules/calculator/screens/CalculatorScreen.tsx');
const detail=read('src/modules/quotes/screens/QuoteDetailScreen.tsx');
const services=read('src/modules/services/screens/ServicesScreen.tsx');
ok('centraliza diária padrão de P.O. em 30000 centavos',/DEFAULT_PO_DAILY_CENTS=30000/.test(helper));
ok('helper usa equipe precificada e faz fallback para base/padrão',/teamDaily>0/.test(helper)&&/baseDaily>0\?baseDaily:DEFAULT_PO_DAILY_CENTS/.test(helper));
ok('novo orçamento usa helper compartilhado e adiciona P.O. quando equipe existe mas soma zero',/serviceTeamDailyCents\(service\)/.test(wizard)&&/teamDailyCents>0\?mapped:\[\.\.\.mapped,\{label:'P\.O\. responsável'/.test(wizard));
ok('calculadora usa helper e injeta P.O. quando a equipe não possui diária positiva',/serviceTeamDailyCents\(service\)<=0/.test(calc)&&/serviceReferenceDailyCents\(service\)/.test(calc));
ok('edição de orçamento usa a mesma referência diária',/serviceReferenceDailyCents/.test(detail)&&!/DEFAULT_PO_DAILY_CENTS=30000/.test(detail));
ok('composição de serviços preserva funções sem preço e acrescenta P.O. fallback',/unpricedMembers/.test(services)&&/serviceReferenceDailyCents\(service\)/.test(services));
for(const [name,pass] of checks)console.log(`${pass?'OK':'FAIL'} - ${name}`);
const passed=checks.filter(([,pass])=>pass).length;
console.log(`\n${passed}/${checks.length} checks OK`);
if(passed!==checks.length)process.exit(1);
