function translateCore(core:string,locale:Locale){
  if(locale==='pt-BR')return core;
  const pair=exact[core];
  if(pair)return locale==='en-US'?pair[0]:pair[1];
  // Padrões dinâmicos comuns que chegam como uma única string.
  let m:RegExpMatchArray|null;
  if((m=core.match(/^(\d+) item\(ns\) pedem atenção$/)))return locale==='en-US'?`${m[1]} item(s) need attention`:`${m[1]} elemento(s) requieren atención`;
  if((m=core.match(/^(\d+) tarefa\(s\) atrasada\(s\)$/)))return locale==='en-US'?`${m[1]} overdue task(s)`:`${m[1]} tarea(s) atrasada(s)`;
  if((m=core.match(/^(\d+) resultado\(s\)$/)))return locale==='en-US'?`${m[1]} result(s)`:`${m[1]} resultado(s)`;
  if((m=core.match(/^(\d+) projeto\(s\)$/)))return locale==='en-US'?`${m[1]} project(s)`:`${m[1]} proyecto(s)`;
  if((m=core.match(/^(\d+) serviço\(s\)$/)))return locale==='en-US'?`${m[1]} service(s)`:`${m[1]} servicio(s)`;
  if((m=core.match(/^Página (\d+) de (\d+)$/)))return locale==='en-US'?`Page ${m[1]} of ${m[2]}`:`Página ${m[1]} de ${m[2]}`;
  if((m=core.match(/^Válida até (.+)$/)))return locale==='en-US'?`Valid until ${m[1]}`:`Válida hasta ${m[1]}`;
  if((m=core.match(/^Válido até (.+)$/)))return locale==='en-US'?`Valid until ${m[1]}`:`Válido hasta ${m[1]}`;
  if((m=core.match(/^Validade: (\d+) dias$/)))return locale==='en-US'?`Validity: ${m[1]} days`:`Validez: ${m[1]} días`;
  if((m=core.match(/^Plano (.+)$/)))return locale==='en-US'?`Plan ${m[1]}`:`Plan ${m[1]}`;
  if((m=core.match(/^(\d+) clientes$/)))return locale==='en-US'?`${m[1]} clients`:`${m[1]} clientes`;
  if((m=core.match(/^(\d+) dias restantes$/)))return locale==='en-US'?`${m[1]} days remaining`:`${m[1]} días restantes`;
  if((m=core.match(/^(\d+) dia\(s\) · (\d+) pessoa\(s\)$/)))return locale==='en-US'?`${m[1]} day(s) · ${m[2]} person(s)`:`${m[1]} día(s) · ${m[2]} persona(s)`;
  if((m=core.match(/^Resposta registrada por (.+)\.$/)))return locale==='en-US'?`Response recorded by ${m[1]}.`:`Respuesta registrada por ${m[1]}.`;
  if((m=core.match(/^Versão (.+)$/)))return locale==='en-US'?`Version ${m[1]}`:`Versión ${m[1]}`;
  if((m=core.match(/^Desconto aplicado: (.+)$/)))return locale==='en-US'?`Discount applied: ${m[1]}`:`Descuento aplicado: ${m[1]}`;
  if((m=core.match(/^Desconto \((.+)\)$/)))return locale==='en-US'?`Discount (${m[1]})`:`Descuento (${m[1]})`;
  if((m=core.match(/^Pagamento: (.+)$/)))return locale==='en-US'?`Payment: ${m[1]}`:`Pago: ${m[1]}`;
  if((m=core.match(/^PIX: (.+)$/)))return `PIX: ${m[1]}`;
  if((m=core.match(/^PROJETOS · (\d+) ATRASOS$/)))return locale==='en-US'?`PROJECTS · ${m[1]} OVERDUE`:`PROYECTOS · ${m[1]} ATRASOS`;
  if((m=core.match(/^Coluna (\d+) · (Ativo|Desativado)$/)))return locale==='en-US'?`Column ${m[1]} · ${m[2]==='Ativo'?'Active':'Disabled'}`:`Columna ${m[1]} · ${m[2]==='Ativo'?'Activo':'Desactivado'}`;
  if((m=core.match(/^Selecionar cor (.+)$/)))return locale==='en-US'?`Select color ${m[1]}`:`Seleccionar color ${m[1]}`;
  return core;
}

export function tr(value:string,locale:Locale=activeLocale){
  if(!value||locale==='pt-BR')return value;
  const leading=value.match(/^\s*/)?.[0]??'';const trailing=value.match(/\s*$/)?.[0]??'';
  const core=value.trim();if(!core)return value;
  return leading+translateCore(core,locale)+trailing;
}

function localizeNode(node:ReactNode):ReactNode{
  if(typeof node==='string')return tr(node);
  if(Array.isArray(node))return node.map(localizeNode);
  return node;
}

