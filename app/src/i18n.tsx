type Ctx={locale:Locale;setLocale:(v:Locale)=>void;t:(key:NavKey)=>string;tr:(value:string)=>string};
const I18nContext=createContext<Ctx>({locale:'pt-BR',setLocale:()=>undefined,t:key=>nav['pt-BR'][key],tr:value=>value});
export function I18nProvider({children}:{children:ReactNode}){
  const[locale,setLocaleState]=useState<Locale>('pt-BR');
  useEffect(()=>{if(Platform.OS==='web'&&typeof localStorage!=='undefined'){const saved=localStorage.getItem(KEY) as Locale|null;if(saved&&nav[saved]){activeLocale=saved;setLocaleState(saved)}}},[]);
  const setLocale=(v:Locale)=>{activeLocale=v;setLocaleState(v);if(Platform.OS==='web'&&typeof localStorage!=='undefined')localStorage.setItem(KEY,v)};
  useEffect(()=>{activeLocale=locale},[locale]);
  const value=useMemo(()=>({locale,setLocale,t:(key:NavKey)=>nav[locale][key]??key,tr:(text:string)=>tr(text,locale)}),[locale]);
  // key força a árvore não-consumidora do contexto a atualizar textos legados traduzidos via wrapper.
  return <I18nContext.Provider value={value}><React.Fragment key={locale}>{children}</React.Fragment></I18nContext.Provider>;
}
